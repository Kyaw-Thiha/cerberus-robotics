"""Out-of-tree Isaac Lab Arena assets: the stock Go2 embodiment, a GRScenes background, a waypoint task.

Everything Arena/isaaclab related is imported lazily (inside ``_build_arena_classes`` / function bodies), so this
module imports with plain python. The Arena classes are created on first use and cached; creating them runs
Arena's ``@register_asset`` / ``@register_task`` decorators, which is the registration. Call
``register_go2_assets()`` AFTER the Isaac app has launched (Arena pulls in ``pxr``/Kit modules).

What was learned about Arena (read from ``third_party/IsaacLab-Arena`` at ``main`` 311d0f0fc, fetched by
``scripts/fetch_arena.py``; Lab submodule bb0c8e1b9, Python >=3.12, Isaac Sim 6.1.0 container)
-------------------------------------------------------------------------------------------------------
Embodiments (``isaaclab_arena/embodiments/``)
  * ``embodiment_base.py::EmbodimentBase(PlaceableAsset)``; subclass sets class attr ``name`` and in
    ``__init__(enable_cameras, initial_pose, concatenate_observation_terms, arm_mode)`` fills
    ``scene_config`` (a configclass with a ``robot: ArticulationCfg`` field; scene key ``"robot"``),
    ``action_config``, ``observation_config``, ``event_config`` (+ optional reward/termination/camera cfgs).
    ``get_scene_cfg()/get_action_cfg()/get_observation_cfg()/get_events_cfg()`` are what the builder reads.
    Example: ``franka/franka.py`` (``FrankaJointPosEmbodiment``: ``JointPositionActionCfg``, ObsGroup,
    ``robot.replace(prim_path="{ENV_REGEX_NS}/Robot")``) and ``g1/g1.py``. Poses are XYZW
    (``utils/pose.py::Pose(position_xyz, rotation_xyzw)``).
  * Registration: ``assets/register.py::@register_asset`` -> ``assets/registries.py::AssetRegistry``
    (singleton, keyed by class ``name``; ``AssetRegistry().get_asset_by_name("go2")()`` instantiates). The
    registry lazily imports Arena's own libraries (``ensure_assets_registered``) but NOT external modules, so
    an external repo registers by importing its module (done here by ``register_go2_assets``).
  * No quadruped exists in Arena; the only precedent for locomotion is G1 (``isaaclab_arena_g1``).
Backgrounds / scenes
  * ``assets/background.py::Background(Object)`` args ``name, usd_path, object_min_z, prim_path, initial_pose,
    reset_nested_physics``; object type BASE; spawned through ``UsdFileCfg`` at ``{ENV_REGEX_NS}/<name>`` (cloned
    per env, ``replicate_physics=False``) unless ``prim_path`` is a non-env path such as ``/World/Scene``
    (then spawned once and shared by all envs).
  * ``assets/background_library.py``: ``LibraryBackground`` subclasses with ``@register_asset``; Lightwheel
    RoboCasa kitchens are generated by ``assets/lightwheel_kitchen_factory.py`` as
    ``lightwheel_kitchen_<layout>_<style>`` (USD fetched through ``lightwheel_sdk`` at construction).
  * ``scene/scene.py::Scene(assets=[...])`` -> ``get_scene_cfg()`` builds the SceneCfg configclass.
Tasks (``isaaclab_arena/tasks/``)
  * ``task_base.py::TaskBase``: abstract ``get_scene_cfg, get_termination_cfg, get_events_cfg, get_mimic_env_cfg,
    get_metrics``; ``@register_task`` (keyed by class name). The only stock goal task, ``GoalPoseTask``, tracks a
    scene *object* (``object: Asset``), not the robot, and ``NoTask`` has no success term, so neither fits a
    waypoint-reach check on a robot: ``WaypointReachTask`` below is a trivial replacement.
  * Metrics: ``metrics/success_rate.py::SuccessRateMetric`` needs a termination term named ``success``.
Environments (``isaaclab_arena/environments/``)
  * ``isaaclab_arena_environment.py::IsaacLabArenaEnvironment(name, scene, embodiment, task, ...)``.
  * ``arena_env_builder_cfg.py::ArenaEnvBuilderCfg(num_envs, env_spacing=30.0, seed, solve_relations, device=
    "cuda:0", presets, ...)``; ``arena_env_builder.py::ArenaEnvBuilder(arena_env, cfg)`` ->
    ``.make_registered()`` (gym-registers and ``gym.make``s a ``IsaacLabArenaManagerBasedRLEnv``; num_envs and
    device flow in through the builder cfg via ``parse_env_cfg``) or ``.compose_manager_cfg()`` for the raw cfg.
    Default control rate 15 Hz (sim dt 1/120, decimation 8); ``rewards`` / ``curriculum`` / ``commands`` are
    forced to None in ``IsaacLabArenaManagerBasedRLEnvCfg``.
  * Lab 3.0 data access: ``asset.data.root_pose_w.torch`` (a proxy array); ``env.arena_world.get_pose_e(key)``.
External repo guide: ``docs/pages/arena_in_your_repo/{external_installation,external_environments,
external_tasks_and_embodiments}.rst`` (install Arena unmodified, e.g. ``pip install -e``, then register assets
from your own package).

Design here
-----------
* ``GO2_EMBODIMENT`` (pure ``EmbodimentCfg``) names the 12 leg joints; ``Go2Embodiment`` is a thin wrapper over
  ``isaaclab_assets.robots.unitree.UNITREE_GO2_CFG``: joint-position actions on the legs addressed BY NAME
  (``preserve_order=True``), observations = leg joint pos/vel, base lin/ang vel, projected gravity, no sensors.
* ``GRScenesBackground`` spawns one plain GRScenes USD as the scene; ``spawn_pose`` is where the robot starts in
  the scene frame (the scene is shifted so that point lands on the env origin).
* ``WaypointReachTask`` terminates with ``success`` when the robot base is within ``radius`` of an env-local
  waypoint.
* ``go2_arx5`` hook: ``register_go2_arx5_assets`` calls ``go2_arx5_embodiment.register_go2_arx5_assets`` (W2b).

# UNVERIFIED: none of the Arena-side classes has been instantiated yet (needs a pod with Sim 6.1 / Lab 3.0).
"""

from __future__ import annotations

from types import SimpleNamespace
from typing import Any

from common.cerberus_description.embodiment import EmbodimentCfg
from common.cerberus_description.go2_arx5_spec import GO2_LEG_JOINTS
from common.cerberus_worlds.arena_assets import (
    ensure_mdl_system_path,
    spawn_pose_to_background_pose,
)

GO2_ARENA_NAME = "go2"
GO2_ARX5_ARENA_NAME = "go2_arx5"
GO2_EMBODIMENT = EmbodimentCfg(
    name=GO2_ARENA_NAME,
    articulation_cfg_entry_point="isaaclab_assets.robots.unitree:UNITREE_GO2_CFG",
    joint_groups={"legs": tuple(GO2_LEG_JOINTS)},
)

ROBOT_SCENE_KEY = "robot"
ROBOT_PRIM_PATH = "{ENV_REGEX_NS}/Robot"
SHARED_SCENE_PRIM_PATH = "/World/Scene"
GRSCENES_ASSET_NAME = "grscenes_scene"
# Joint-position action = default_pose + scale * action, the Isaac Lab Go2 locomotion convention.
ACTION_SCALE = 0.25
DEFAULT_WAYPOINT_XY = (2.0, 0.0)  # env-local metres
DEFAULT_WAYPOINT_RADIUS_M = 0.5
DEFAULT_EPISODE_LENGTH_S = 10.0


# ---------------------------------------------------------------------------------------------------------
# Waypoint math (shared by the Arena task and the plain-USD backend). torch is imported lazily.
# ---------------------------------------------------------------------------------------------------------
def _to_torch(x: Any) -> Any:
    """Torch view of Isaac Lab data: a tensor (Lab 2.3), a ``.torch`` proxy array or a warp array (Lab 3.0)."""
    if hasattr(x, "torch"):
        return x.torch
    import torch

    if isinstance(x, torch.Tensor):
        return x
    import warp as wp  # UNVERIFIED: fallback for raw warp arrays on the 3.0 line

    return wp.to_torch(x)


def robot_xy_env(env: Any, asset_name: str = ROBOT_SCENE_KEY) -> Any:
    """Robot base xy relative to its env origin, shape (num_envs, 2)."""
    asset = env.scene[asset_name]
    pos = _to_torch(asset.data.root_pos_w)
    return (pos - env.scene.env_origins)[:, :2]


def waypoint_distance_xy(
    env: Any, waypoint_xy: tuple[float, float], asset_name: str = ROBOT_SCENE_KEY
) -> Any:
    """Planar distance from the robot base to an env-local waypoint, shape (num_envs,)."""
    import torch

    target = torch.tensor(waypoint_xy, dtype=torch.float32, device=env.device)
    return torch.linalg.norm(robot_xy_env(env, asset_name) - target, dim=-1)


def waypoint_reached(
    env: Any,
    waypoint_xy: tuple[float, float] = DEFAULT_WAYPOINT_XY,
    radius: float = DEFAULT_WAYPOINT_RADIUS_M,
    asset_name: str = ROBOT_SCENE_KEY,
) -> Any:
    """Termination term: True where the robot is within `radius` of the waypoint."""
    return waypoint_distance_xy(env, waypoint_xy, asset_name) < radius


def waypoint_reward(
    env: Any,
    waypoint_xy: tuple[float, float] = DEFAULT_WAYPOINT_XY,
    asset_name: str = ROBOT_SCENE_KEY,
) -> Any:
    """Reward term: negative distance to the waypoint (dense, trivially shaped)."""
    return -waypoint_distance_xy(env, waypoint_xy, asset_name)


# ---------------------------------------------------------------------------------------------------------
# Shared MDP pieces (Arena embodiment and plain-USD backend)
# ---------------------------------------------------------------------------------------------------------
def make_go2_mdp_cfgs(
    embodiment: EmbodimentCfg = GO2_EMBODIMENT, asset_name: str = ROBOT_SCENE_KEY
) -> SimpleNamespace:
    """Build the legs-only MDP config pieces for `embodiment` (needs isaaclab; call after app launch).

    Returns a namespace with ``robot_cfg`` (ArticulationCfg, prim path ``{ENV_REGEX_NS}/Robot``),
    ``actions`` / ``observations`` (configclass *instances*) and ``legs`` (joint names).

    Only the ``legs`` joint group is driven or observed, addressed by name with ``preserve_order=True`` so the
    action/observation order equals ``embodiment.joint_groups['legs']`` regardless of USD joint order. Other
    joints (the ARX5 arm of go2_arx5) keep their default-pose PD targets. Zero action = default standing pose.
    """
    from isaaclab.envs import mdp
    from isaaclab.managers import ObservationGroupCfg as ObsGroup
    from isaaclab.managers import ObservationTermCfg as ObsTerm
    from isaaclab.managers import SceneEntityCfg
    from isaaclab.utils import configclass

    legs = tuple(embodiment.joint_groups["legs"])

    def _legs() -> Any:
        return SceneEntityCfg(asset_name, joint_names=list(legs), preserve_order=True)

    @configclass
    class Go2ActionsCfg:
        legs_pos = mdp.JointPositionActionCfg(
            asset_name=asset_name,
            joint_names=list(legs),
            preserve_order=True,
            scale=ACTION_SCALE,
            use_default_offset=True,
        )

    @configclass
    class Go2ObservationsCfg:
        @configclass
        class PolicyCfg(ObsGroup):
            joint_pos = ObsTerm(func=mdp.joint_pos_rel, params={"asset_cfg": _legs()})
            joint_vel = ObsTerm(func=mdp.joint_vel_rel, params={"asset_cfg": _legs()})
            base_lin_vel = ObsTerm(func=mdp.base_lin_vel)
            base_ang_vel = ObsTerm(func=mdp.base_ang_vel)
            projected_gravity = ObsTerm(func=mdp.projected_gravity)

            def __post_init__(self):
                self.enable_corruption = False
                self.concatenate_terms = False

        policy: PolicyCfg = PolicyCfg()

    robot_cfg = embodiment.resolve().replace(prim_path=ROBOT_PRIM_PATH)
    return SimpleNamespace(
        robot_cfg=robot_cfg,
        actions=Go2ActionsCfg(),
        observations=Go2ObservationsCfg(),
        legs=legs,
    )


# ---------------------------------------------------------------------------------------------------------
# Arena classes (lazy)
# ---------------------------------------------------------------------------------------------------------
_ARENA_CLASSES: dict[str, type] | None = None


def _build_arena_classes() -> dict[str, type]:
    """Define (and thereby register) the Arena classes. Needs Arena + isaaclab importable (app launched)."""
    from functools import partial

    from isaaclab.assets import ArticulationCfg
    from isaaclab.managers import EventTermCfg
    from isaaclab.utils import configclass
    from isaaclab_arena.assets.background import Background
    from isaaclab_arena.assets.register import register_asset, register_task
    from isaaclab_arena.embodiments.embodiment_base import EmbodimentBase
    from isaaclab_arena.metrics.success_rate import SuccessRateMetric
    from isaaclab_arena.progress_tracking.completion_criteria import CompletionCriteria
    from isaaclab_arena.tasks.task_base import TaskBase
    from isaaclab_arena.tasks.task_termination_cfg import TaskTerminationCfg
    from isaaclab_arena.terms.events import reset_all_articulation_joints
    from isaaclab_arena.utils.pose import Pose

    @configclass
    class Go2SceneCfg:
        """Scene additions from the embodiment: just the robot (no sensors)."""

        robot: ArticulationCfg | None = None

    @configclass
    class Go2EventCfg:
        reset_all = EventTermCfg(func=reset_all_articulation_joints, mode="reset")

    @register_asset
    class Go2Embodiment(EmbodimentBase):
        """Stock Unitree Go2 (12 DoF, legs only) wrapping ``UNITREE_GO2_CFG``."""

        name = GO2_ARENA_NAME
        # Arena `main` (Lab 3.0 GA line) registers by `registry_name`; the older pin reads `name`. Keep both.
        registry_name = GO2_ARENA_NAME
        tags = ["embodiment"]

        def __init__(
            self,
            enable_cameras: bool = False,
            initial_pose: Pose | None = None,
            concatenate_observation_terms: bool = False,
            arm_mode: Any = None,
        ):
            super().__init__(
                enable_cameras, initial_pose, concatenate_observation_terms, arm_mode
            )
            cfgs = make_go2_mdp_cfgs(GO2_EMBODIMENT)
            self.scene_config = Go2SceneCfg(robot=cfgs.robot_cfg)
            self.action_config = cfgs.actions
            self.observation_config = cfgs.observations
            self.observation_config.policy.concatenate_terms = (
                self.concatenate_observation_terms
            )
            self.event_config = Go2EventCfg()
            self.joint_groups = dict(GO2_EMBODIMENT.joint_groups)

    class GRScenesBackground(Background):
        """One plain GRScenes USD (``start_result_navigation.usd``) as the whole scene.

        Args:
            usd_path: scene USD.
            spawn_pose: ``(x, y, yaw_rad)`` robot start in the scene frame; the scene is shifted/rotated so
                that point is the env origin (where the robot spawns).
            mdl_path: GRScenes ``Materials`` dir; added to ``MDL_SYSTEM_PATH``. Must already be set before
                the app launches to take effect (scripts/arena_spike_go2.py does that); set here as a
                best effort.
            shared: spawn once at ``/World/Scene`` for all envs instead of one copy per env (a multi-room
                home x 16 copies is heavy). With ``shared=True`` use ``env_spacing`` 0 so every robot starts
                at the spawn point (envs are isolated by collision filtering).
            reset_nested_physics: Arena's nested-physics reset scan; off by default (navigation USD is static;
                the scan walks the whole USD).
        """

        tags = ["background", "grscenes"]

        def __init__(
            self,
            usd_path: str,
            spawn_pose: tuple[float, float, float] = (0.0, 0.0, 0.0),
            mdl_path: str | None = None,
            *,
            name: str = GRSCENES_ASSET_NAME,
            object_min_z: float = -0.5,
            shared: bool = False,
            reset_nested_physics: bool = False,
            **kwargs,
        ):
            ensure_mdl_system_path(mdl_path)
            position, rotation_xyzw = spawn_pose_to_background_pose(spawn_pose)
            super().__init__(
                name=name,
                tags=list(self.tags),
                usd_path=str(usd_path),
                object_min_z=object_min_z,
                prim_path=SHARED_SCENE_PRIM_PATH if shared else None,
                initial_pose=Pose(position_xyz=position, rotation_xyzw=rotation_xyzw),
                reset_nested_physics=reset_nested_physics,
                **kwargs,
            )
            self.mdl_path = mdl_path
            self.spawn_pose = tuple(spawn_pose)

    @register_task
    class WaypointReachTask(TaskBase):
        """Trivial task: success when the robot base is within `radius` m of an env-local waypoint."""

        def __init__(
            self,
            waypoint_xy: tuple[float, float] = DEFAULT_WAYPOINT_XY,
            radius: float = DEFAULT_WAYPOINT_RADIUS_M,
            episode_length_s: float = DEFAULT_EPISODE_LENGTH_S,
            asset_name: str = ROBOT_SCENE_KEY,
        ):
            super().__init__(
                episode_length_s=episode_length_s,
                task_description=f"Reach waypoint {tuple(waypoint_xy)} within {radius} m",
            )
            self.waypoint_xy = tuple(waypoint_xy)
            self.radius = radius
            self.asset_name = asset_name

        def get_scene_cfg(self) -> Any:
            return None

        def get_termination_cfg(self) -> Any:
            # Arena `main` requires TaskTerminationCfg (success = CompletionCriteria, timeout_s), not a raw
            # configclass of TerminationTermCfg.
            return TaskTerminationCfg(
                timeout_s=self.episode_length_s,
                success=[
                    CompletionCriteria(
                        name="reach_waypoint",
                        predicate_sequence=[
                            partial(
                                waypoint_reached,
                                waypoint_xy=self.waypoint_xy,
                                radius=self.radius,
                                asset_name=self.asset_name,
                            )
                        ],
                    )
                ],
            )

        def get_events_cfg(self) -> Any:
            return None

        def get_mimic_env_cfg(self, arm_mode: Any) -> Any:
            return None

        def get_metrics(self) -> list:
            return [SuccessRateMetric()]

    return {
        "Go2Embodiment": Go2Embodiment,
        "GRScenesBackground": GRScenesBackground,
        "WaypointReachTask": WaypointReachTask,
    }


def get_arena_classes() -> dict[str, type]:
    """The Arena classes (``Go2Embodiment``, ``GRScenesBackground``, ``WaypointReachTask``), built on first use."""
    global _ARENA_CLASSES
    if _ARENA_CLASSES is None:
        _ARENA_CLASSES = _build_arena_classes()
    return _ARENA_CLASSES


def __getattr__(
    name: str,
) -> (
    Any
):  # PEP 562: `from ...go2_embodiment import GRScenesBackground` after app launch
    if name in ("Go2Embodiment", "GRScenesBackground", "WaypointReachTask"):
        return get_arena_classes()[name]
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def register_go2_assets() -> dict[str, type]:
    """Register the Go2 Arena embodiment (and the GRScenes background + waypoint task). Idempotent.

    Imports Arena lazily: call after the Isaac app has launched.
    """
    return get_arena_classes()


def register_go2_arx5_assets() -> dict[str, type]:
    """Register the fixed-base fused Go2 + ARX5 Arena embodiment (20 DoF: legs, joint1..6, gripper joint7/joint8).

    Thin hook: the embodiment, its kitchen pick-and-place environment factory and the W2b notes live in
    ``go2_arx5_embodiment``. Imports Arena lazily: call after the Isaac app has launched.
    """
    from common.cerberus_worlds.arena_assets import go2_arx5_embodiment

    return go2_arx5_embodiment.register_go2_arx5_assets()


def register_embodiment_cfg(cfg: EmbodimentCfg) -> str:
    """Register the Arena embodiment for `cfg` and return its Arena asset name."""
    if cfg.name == GO2_ARENA_NAME:
        register_go2_assets()
        return GO2_ARENA_NAME
    if cfg.name == GO2_ARX5_ARENA_NAME:
        register_go2_arx5_assets()
        return GO2_ARX5_ARENA_NAME
    raise ValueError(
        f"No Arena embodiment for {cfg.name!r}; known: {[GO2_ARENA_NAME, GO2_ARX5_ARENA_NAME]}"
    )
