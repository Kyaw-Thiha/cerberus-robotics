#!/usr/bin/env python3
"""Generate docs/backend_support.md from common/cerberus_policies/cards/*.yaml.

Pure Python (no Isaac, torch or ROS). Usage:
    pixi run backend-table            # rewrite docs/backend_support.md
    python scripts/gen_backend_table.py --check   # exit 1 if the file is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.cerberus_policies.backend_card import (
    CARDS_DIR,
    BackendCard,
    load_all_cards,
)

OUTPUT = REPO_ROOT / "docs" / "backend_support.md"

HEADER = """# Backend support

<!-- GENERATED by scripts/gen_backend_table.py from common/cerberus_policies/cards/*.yaml. Do not edit by hand; run `pixi run backend-table`. -->

Support level is what the evidence proves today; target is what we intend to reach. We do not train everything.

| Level | Meaning | Evidence required |
|---|---|---|
| L0 | Documented | Backend card only, no code |
| L1 | Integrated | Adapter exists and passes contract tests (loads, `act()` returns correct shapes, sensor needs validate against a rig) |
| L2 | Evaluated | Run on our scenes or shared evals with released weights or without training; numbers recorded |
| L3 | Trained by us | Trained and evaluated by us; result recorded in a report |

Architecture: **modular** backends consume a map or other upstream module output; **fused** backends consume raw sensor streams and train their perception encoder inside the policy. Both plug in at the same boundary.

"""

COLUMNS = ("Slot", "Backend", "Paradigm", "Architecture", "Support level", "Target", "Evidence")


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _evidence(card: BackendCard) -> str:
    if not card.evidence:
        return "none"
    links = []
    for e in card.evidence:
        ref, kind = e["ref"], e["kind"]
        if kind == "commit":
            links.append(f"commit `{ref}`")
            continue
        # links are relative to docs/, where this file lives
        target = ref[len("docs/"):] if ref.startswith("docs/") else f"../{ref}"
        links.append(f"[{Path(ref).name}]({target})")
    return ", ".join(links)


def render(cards_dir: Path = CARDS_DIR) -> str:
    cards = load_all_cards(cards_dir)
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    for c in cards:
        row = (c.slot, f"`{c.name}`", c.paradigm, c.architecture, c.support_level, c.target_support_level, _evidence(c))
        lines.append("| " + " | ".join(_cell(x) for x in row) + " |")
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is out of date; run `pixi run backend-table`", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(load_all_cards())} backends)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
